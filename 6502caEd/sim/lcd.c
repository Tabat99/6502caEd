/* Convert display position (col, row) to DDRAM address */
static int ddram_addr(const lcd_t *lcd, int col, int row) {
    /* HD44780 DDRAM layout:
     * 2-line: row 0 starts at $00, row 1 starts at $40
     * 4-line (20×4): row 0=$00, row 1=$40, row 2=$14, row 3=$54 */
    static const int row_base[4] = {0x00, 0x40, 0x14, 0x54};
    if (row < 0 || row >= lcd->rows) return -1;
    if (col < 0 || col >= lcd->cols) return -1;
    return row_base[row] + col;
}

/* Set busy flag for a given duration in nanoseconds */
static void set_busy(lcd_t *lcd, uint64_t duration_ns) {
    if (!lcd->strict_timing) return;
    uint64_t cycles = (duration_ns * lcd->cpu_hz) / 1000000000UL;
    lcd->busy_until_cycles = lcd->cpu_cycles + cycles;
}

/* Advance address counter with wrap */
static void advance_ac(lcd_t *lcd) {
    if (lcd->cgram_mode) {
        if (lcd->increment)
            lcd->ac = (lcd->ac + 1) & 0x3F;
        else
            lcd->ac = (lcd->ac - 1) & 0x3F;
    } else {
        /* DDRAM advance:
         * 1-line display: sequential $00-$4F (80 bytes), wraps at $50->$00
         * 2/4-line display: bank1 $00-$27, skip $28-$3F, bank2 $40-$67 */
        int next = lcd->increment ? (int)lcd->ac + 1 : (int)lcd->ac - 1;
        if (lcd->two_line) {
            /* Two-bank address space */
            if (next < 0)               next = 0x67;
            if (next >= 0x28 && next <= 0x3F)
                next = lcd->increment ? 0x40 : 0x27;
            if (next > 0x67)            next = 0x00;
        } else {
            /* Single bank: $00-$4F */
            if (next < 0)    next = 0x4F;
            if (next > 0x4F) next = 0x00;
        }
        lcd->ac = (uint8_t)next;
    }
}

/* Execute a full 8-bit command byte */
static void execute_command(lcd_t *lcd, bool rs, uint8_t data) {
    if (!rs) {
        /* Instruction register */
        if (data == 0x01) {
            /* Clear Display */
            memset(lcd->ddram, 0x20, sizeof(lcd->ddram));
            lcd->ac = 0;
            lcd->cgram_mode = false;
            lcd->shift_offset = 0;
            set_busy(lcd, LCD_TIME_CLEAR_NS);
        } else if (data == 0x02 || data == 0x03) {
            /* Return Home */
            lcd->ac = 0;
            lcd->cgram_mode = false;
            lcd->shift_offset = 0;
            set_busy(lcd, LCD_TIME_CLEAR_NS);
        } else if ((data & 0xFC) == 0x04) {
            /* Entry Mode Set: I/D=bit1, S=bit0 */
            lcd->increment = (data & 0x02) != 0;
            lcd->shift_on  = (data & 0x01) != 0;
            set_busy(lcd, LCD_TIME_CMD_NS);
        } else if ((data & 0xF8) == 0x08) {
            /* Display On/Off: D=bit2, C=bit1, B=bit0 */
            lcd->display_on = (data & 0x04) != 0;
            lcd->cursor_on  = (data & 0x02) != 0;
            lcd->blink_on   = (data & 0x01) != 0;
            set_busy(lcd, LCD_TIME_CMD_NS);
        } else if ((data & 0xF0) == 0x10) {
            /* Cursor or Display Shift: S/C=bit3, R/L=bit2 */
            bool display_shift = (data & 0x08) != 0;
            bool right         = (data & 0x04) != 0;
            if (display_shift) {
                /* Offset selects the leftmost visible DDRAM column. */
                lcd->shift_offset += right ? -1 : 1;
                /* Wrap within 40-column DDRAM bank */
                if (lcd->shift_offset >= 40)  lcd->shift_offset -= 40;
                if (lcd->shift_offset < 0)    lcd->shift_offset += 40;
            } else {
                /* Cursor shift: temporarily override increment direction */
                bool saved = lcd->increment;
                lcd->increment = right;
                advance_ac(lcd);
                lcd->increment = saved;
            }
            set_busy(lcd, LCD_TIME_CMD_NS);
        } else if ((data & 0xE0) == 0x20) {
            /* Function Set: DL=bit4, N=bit3, F=bit2 */
            lcd->bus_8bit  = (data & 0x10) != 0;
            lcd->two_line  = (data & 0x08) != 0;
            lcd->font_5x10 = (data & 0x04) != 0;
            if (!lcd->initialised) {
                lcd->init_step++;
                /* Datasheet requires 3 Function Set commands before BF is valid.
                 * No busy delay during init — host code must insert delays.
                 * Commands are never silently ignored during init (see above). */
                if (lcd->init_step >= 3) lcd->initialised = true;
                set_busy(lcd, LCD_TIME_CMD_NS);
            } else {
                set_busy(lcd, LCD_TIME_CMD_NS);
            }
        } else if ((data & 0xC0) == 0x40) {
            /* Set CGRAM Address */
            lcd->ac = data & 0x3F;
            lcd->cgram_mode = true;
            set_busy(lcd, LCD_TIME_CMD_NS);
        } else if (data & 0x80) {
            /* Set DDRAM Address */
            lcd->ac = data & 0x7F;
            lcd->cgram_mode = false;
            set_busy(lcd, LCD_TIME_CMD_NS);
        }
    } else {
        /* Data register write */
        if (lcd->cgram_mode) {
            lcd->cgram[lcd->ac & 0x3F] = data;
        } else {
            if (lcd->ac < LCD_DDRAM_SIZE)
                lcd->ddram[lcd->ac] = data;
            if (lcd->shift_on) {
                lcd->shift_offset += lcd->increment ? 1 : -1;
                if (lcd->shift_offset >= 40) lcd->shift_offset -= 40;
                if (lcd->shift_offset < 0)   lcd->shift_offset += 40;
            }
        }
        advance_ac(lcd);
        set_busy(lcd, LCD_TIME_WRITE_NS);
    }
}

/* -------------------------------------------------------------------------
 * Public API
 * ------------------------------------------------------------------------- */

void lcd_init(lcd_t *lcd, int cols, int rows, uint64_t cpu_hz) {
    memset(lcd, 0, sizeof(*lcd));
    lcd->cols    = cols > 0 ? cols : 20;
    lcd->rows    = rows > 0 ? rows : 4;
    lcd->cpu_hz  = cpu_hz > 0 ? cpu_hz : 1000000;
    lcd_reset(lcd);
}

void lcd_reset(lcd_t *lcd) {
    memset(lcd->ddram, 0x20, sizeof(lcd->ddram));
    memset(lcd->cgram, 0x00, sizeof(lcd->cgram));
    lcd->ac             = 0;
    lcd->cgram_mode     = false;
    lcd->display_on     = false;
    lcd->cursor_on      = false;
    lcd->blink_on       = false;
    lcd->increment      = true;
    lcd->shift_on       = false;
    lcd->bus_8bit       = true;   /* power-on default */
    lcd->two_line       = false;
    lcd->font_5x10      = false;
    lcd->shift_offset   = 0;
    lcd->nibble_pending = false;
    lcd->nibble_high    = 0;
    lcd->busy_until_cycles = 0;
    lcd->init_step      = 0;
    lcd->initialised    = false;
    lcd->blink_cycle    = 0;
    lcd->blink_state    = false;
}

void lcd_tick(lcd_t *lcd) {
    lcd->cpu_cycles++;
    /* Blink: toggle every 0.4s per datasheet (0.4 * cpu_hz cycles) */
    uint64_t blink_period = (lcd->cpu_hz * 2) / 5;
    if (blink_period == 0) blink_period = 400000;
    lcd->blink_cycle++;
    if (lcd->blink_cycle >= blink_period) {
        lcd->blink_cycle = 0;
        lcd->blink_state = !lcd->blink_state;
    }
}

uint8_t lcd_strobe(lcd_t *lcd, bool rs, bool rw, uint8_t data, bool *busy_out) {
    bool busy = lcd->strict_timing &&
                (lcd->cpu_cycles < lcd->busy_until_cycles);
    if (busy_out) *busy_out = busy;

    if (rw) {
        /* Read operation */
        if (!rs) {
            /* Read BF + AC */
            uint8_t result = lcd->ac & 0x7F;
            if (busy) result |= 0x80;
            if (!lcd->bus_8bit) {
                /* 4-bit: return high nibble first */
                if (!lcd->nibble_pending) {
                    lcd->nibble_pending = true;
                    lcd->nibble_high = result;
                    return (result >> 4) & 0x0F;
                } else {
                    lcd->nibble_pending = false;
                    return lcd->nibble_high & 0x0F;
                }
            }
            return result;
        } else {
            /* Read data */
            uint8_t result;
            if (lcd->cgram_mode)
                result = lcd->cgram[lcd->ac & 0x3F];
            else
                result = lcd->ac < LCD_DDRAM_SIZE ? lcd->ddram[lcd->ac] : 0x20;
            advance_ac(lcd);
            set_busy(lcd, LCD_TIME_READ_NS);
            if (!lcd->bus_8bit) {
                if (!lcd->nibble_pending) {
                    lcd->nibble_pending = true;
                    lcd->nibble_high = result;
                    return (result >> 4) & 0x0F;
                } else {
                    lcd->nibble_pending = false;
                    return lcd->nibble_high & 0x0F;
                }
            }
            return result;
        }
    } else {
        /* Write operation */
        /* During init, commands must execute regardless of busy flag.
         * Only ignore if busy AND fully initialised. */
        if (busy && lcd->strict_timing && lcd->initialised) return 0xFF;

        if (!lcd->bus_8bit) {
            /* 4-bit mode — assemble byte from two nibbles */
            if (!lcd->nibble_pending) {
                /* First nibble (high bits in D4-D7) */
                lcd->nibble_pending = true;
                lcd->nibble_high    = (data & 0x0F) << 4;
                lcd->nibble_rs      = rs;
                return 0xFF;
            } else {
                /* Second nibble — assemble full byte */
                lcd->nibble_pending = false;
                uint8_t full = lcd->nibble_high | (data & 0x0F);
                execute_command(lcd, lcd->nibble_rs, full);
                return 0xFF;
            }
        } else {
            /* 8-bit mode (LCD power-on state during 4-bit init).
             * In 4-bit interface mode, read_data_pins returns only D4-D7
             * as bits 0-3 (e.g. nibble $3 arrives as data=$03).
             * Shift left 4 so execute_command sees $30 = function set. */
            uint8_t cmd = lcd->is_4bit_iface ? (uint8_t)(data << 4) : data;
            execute_command(lcd, rs, cmd);
            return 0xFF;
        }
    }
}

uint8_t lcd_read_bf_ac(const lcd_t *lcd) {
    bool busy = lcd->strict_timing &&
                (lcd->cpu_cycles < lcd->busy_until_cycles);
    uint8_t result = lcd->ac & 0x7F;
    if (busy) result |= 0x80;
    return result;
}

uint8_t lcd_read_data(const lcd_t *lcd) {
    if (lcd->cgram_mode)
        return lcd->cgram[lcd->ac & 0x3F];
    return lcd->ac < LCD_DDRAM_SIZE ? lcd->ddram[lcd->ac] : 0x20;
}

uint8_t lcd_get_char(const lcd_t *lcd, int col, int row) {
    if (!lcd->display_on) return 0x20;
    /* DDRAM layout for 20x4:
     *   Row 0: 0x00-0x13   Row 1: 0x40-0x53
     *   Row 2: 0x14-0x27   Row 3: 0x54-0x67
     * Display shift applies within each row's 40-column logical space.
     * We compute the shifted column then map to the correct DDRAM address. */
    static const int row_base[4] = {0x00, 0x40, 0x14, 0x54};
    if (row < 0 || row >= lcd->rows) return 0x20;
    if (col < 0 || col >= lcd->cols) return 0x20;
    int shifted_col = (col + lcd->shift_offset + 40) % 40;
    int addr = row_base[row] + shifted_col;
    if (addr >= LCD_DDRAM_SIZE) return 0x20;
    return lcd->ddram[addr];
}

void lcd_get_bitmap(const lcd_t *lcd, uint8_t char_code, uint8_t *out_pixels) {
    if ((char_code & 0xF8) == 0x00) {
        /* CGRAM character — codes 0x00-0x07 (and mirror 0x08-0x0F) */
        int slot = char_code & 0x07;
        for (int r = 0; r < 8; r++)
            out_pixels[r] = lcd->cgram[slot * 8 + r] & 0x1F;
    } else {
        /* CGROM */
        for (int r = 0; r < 8; r++)
            out_pixels[r] = lcd_cgrom[char_code][r] & 0x1F;
    }
}

bool lcd_cursor_at(const lcd_t *lcd, int col, int row) {
    if (!lcd->display_on || !lcd->cursor_on) return false;
    if (!lcd->cgram_mode) {
        int addr = ddram_addr(lcd, col, row);
        if (addr < 0) return false;
        return (lcd->ac == (uint8_t)addr);
    }
    return false;
}

bool lcd_blink_on(const lcd_t *lcd) {
    return lcd->display_on && lcd->blink_on && lcd->blink_state;
}

void lcd_set_cpu_hz(lcd_t *lcd, uint64_t cpu_hz) {
    lcd->cpu_hz = cpu_hz > 0 ? cpu_hz : 1000000;
}

void lcd_set_strict(lcd_t *lcd, bool strict) {
    lcd->strict_timing = strict;
}
